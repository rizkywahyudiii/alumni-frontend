import axios from 'axios';

const api = axios.create({
  baseURL: 'http://localhost:8000',
  headers: {
    'Content-Type': 'application/json',
    'Accept': 'application/json',
  },
  withCredentials: true, // Wajib TRUE
});

// Helper function untuk ambil value dari Cookie browser
const getCookie = (name) => {
  const value = `; ${document.cookie}`;
  const parts = value.split(`; ${name}=`);
  if (parts.length === 2) return parts.pop().split(';').shift();
};

// INTERCEPTOR SAKTI:
// Sebelum request terbang, cek apakah ada cookie XSRF-TOKEN.
// Kalau ada, ambil isinya, decode, dan tempel ke Header X-XSRF-TOKEN.
api.interceptors.request.use((config) => {
  const token = getCookie('XSRF-TOKEN');
  if (token) {
    config.headers['X-XSRF-TOKEN'] = decodeURIComponent(token);
  }
  return config;
});

export default api;